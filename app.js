/* =========================================================
   TOAST
========================================================= */

function showToast(message) {

    let toast =
        document.getElementById("toast");


    if (!toast) {

        toast =
            document.createElement("div");

        toast.id = "toast";

        toast.className = "toast";

        document.body.appendChild(toast);
    }


    toast.textContent = message;

    toast.classList.add("show");


    clearTimeout(window.toastTimer);


    window.toastTimer =
        setTimeout(
            function () {

                toast.classList.remove("show");

            },
            3000
        );
}


/* =========================================================
   DISPLAY PRODUCTS
========================================================= */

function displayProducts() {

    const container =
        document.getElementById(
            "products-container"
        );


    if (!container) {
        return;
    }


    container.innerHTML = "";


    products.forEach(function (product) {

        if (!cardImageStates[product.id]) {

            cardImageStates[product.id] = {

                colorIndex: 0,

                imageIndex: 0
            };
        }


        const state =
            cardImageStates[product.id];


        const selectedColor =
            product.colors[state.colorIndex];


        const image =
            selectedColor.images[state.imageIndex];


        const card =
            document.createElement("div");


        card.className = "card";

        card.dataset.productId =
            product.id;


        card.addEventListener(
            "click",
            function () {

                openProduct(product.id);

            }
        );


        const imageContainer =
            document.createElement("div");


        imageContainer.className =
            "card-image-container";


        const productImage =
            document.createElement("img");


        productImage.src = image;

        productImage.alt = product.name;

        productImage.className =
            "abaya-image";


        imageContainer.appendChild(
            productImage
        );


        if (selectedColor.images.length > 1) {

            const leftButton =
                document.createElement("button");


            leftButton.type = "button";

            leftButton.className =
                "image-arrow left";

            leftButton.innerHTML = "‹";

            leftButton.addEventListener(
                "click",
                function (event) {

                    event.stopPropagation();

                    changeCardImage(
                        product.id,
                        -1
                    );

                }
            );


            const rightButton =
                document.createElement("button");


            rightButton.type = "button";

            rightButton.className =
                "image-arrow right";

            rightButton.innerHTML = "›";


            rightButton.addEventListener(
                "click",
                function (event) {

                    event.stopPropagation();

                    changeCardImage(
                        product.id,
                        1
                    );

                }
            );


            imageContainer.appendChild(
                leftButton
            );

            imageContainer.appendChild(
                rightButton
            );
        }


        card.appendChild(
            imageContainer
        );


        const title =
            document.createElement("h3");


        title.textContent =
            product.name;


        card.appendChild(title);


        const price =
            document.createElement("p");


        price.className = "price";

        price.textContent =
            "$" +
            Number(product.price).toFixed(2);


        card.appendChild(price);


        if (product.colors.length > 0) {

            const colorsContainer =
                document.createElement("div");


            colorsContainer.className =
                "card-colors";


            product.colors.forEach(
                function (color, colorIndex) {

                    const colorButton =
                        document.createElement(
                            "button"
                        );


                    colorButton.type =
                        "button";

                    colorButton.className =
                        "card-color";

                    colorButton.title =
                        color.name;

                    colorButton.style.backgroundColor =
                        getColorValue(
                            color.name
                        );


                    if (
                        colorIndex ===
                        state.colorIndex
                    ) {

                        colorButton.classList.add(
                            "selected"
                        );
                    }


                    colorButton.addEventListener(
                        "click",
                        function (event) {

                            event.stopPropagation();

                            selectCardColor(
                                product.id,
                                colorIndex
                            );

                        }
                    );


                    colorsContainer.appendChild(
                        colorButton
                    );

                }
            );


            card.appendChild(
                colorsContainer
            );
        }


        const addButton =
            document.createElement("button");


        addButton.type = "button";

        addButton.className =
            "add-cart";

        addButton.textContent =
            "Add to Cart";


        addButton.addEventListener(
            "click",
            function (event) {

                event.stopPropagation();


                const currentState =
                    cardImageStates[
                        product.id
                    ];


                const color =
                    product.colors[
                        currentState.colorIndex
                    ];


                const selectedImage =
                    color.images[
                        currentState.imageIndex
                    ];


                addToCart(
                    product,
                    color.name,
                    selectedImage,
                    1
                );

            }
        );


        card.appendChild(
            addButton
        );


        container.appendChild(card);

    });
}


/* =========================================================
   CHANGE CARD IMAGE
========================================================= */

function changeCardImage(productId, direction) {

    const product =
        products.find(function (item) {

            return item.id === productId;

        });


    if (!product) {
        return;
    }


    const state =
        cardImageStates[productId];


    const color =
        product.colors[state.colorIndex];


    if (color.images.length <= 1) {
        return;
    }


    state.imageIndex += direction;


    if (state.imageIndex < 0) {

        state.imageIndex =
            color.images.length - 1;
    }


    if (
        state.imageIndex >=
        color.images.length
    ) {

        state.imageIndex = 0;
    }


    displayProducts();
}


/* =========================================================
   SELECT CARD COLOR
========================================================= */

function selectCardColor(productId, colorIndex) {

    const product =
        products.find(function (item) {

            return item.id === productId;

        });


    if (!product) {
        return;
    }


    const state =
        cardImageStates[productId];


    state.colorIndex =
        colorIndex;


    state.imageIndex = 0;


    displayProducts();
}


/* =========================================================
   OPEN PRODUCT
========================================================= */

function openProduct(productId) {

    currentProduct =
        products.find(function (product) {

            return product.id === productId;

        });


    if (!currentProduct) {
        return;
    }


    currentColorIndex = 0;

    currentImageIndex = 0;

    detailQuantity = 1;


    updateProductModal();


    const modal =
        document.getElementById(
            "product-modal"
        );


    if (modal) {

        modal.classList.add("active");

        document.body.style.overflow =
            "hidden";
    }
}


/* =========================================================
   UPDATE PRODUCT MODAL
========================================================= */

function updateProductModal() {

    if (!currentProduct) {
        return;
    }


    const selectedColor =
        currentProduct.colors[
            currentColorIndex
        ];


    const selectedImage =
        selectedColor.images[
            currentImageIndex
        ];


    const detailImage =
        document.getElementById(
            "detail-image"
        );


    if (detailImage) {

        detailImage.src =
            selectedImage;

        detailImage.alt =
            currentProduct.name;
    }


    const detailName =
        document.getElementById(
            "detail-name"
        );


    if (detailName) {

        detailName.textContent =
            currentProduct.name;
    }


    const detailPrice =
        document.getElementById(
            "detail-price"
        );


    if (detailPrice) {

        detailPrice.textContent =
            "$" +
            Number(
                currentProduct.price
            ).toFixed(2);
    }


    const detailDescription =
        document.getElementById(
            "detail-description"
        );


    if (detailDescription) {

        detailDescription.textContent =
            currentProduct.description;
    }


    const quantity =
        document.getElementById(
            "detail-quantity"
        );


    if (quantity) {

        quantity.textContent =
            detailQuantity;
    }


    const colorsContainer =
        document.getElementById(
            "detail-colors"
        );


    const colorsSection =
        document.getElementById(
            "detail-colors-section"
        );


    if (
        colorsContainer &&
        colorsSection
    ) {

        colorsContainer.innerHTML = "";


        currentProduct.colors.forEach(
            function (color, index) {

                const button =
                    document.createElement(
                        "button"
                    );


                button.type = "button";

                button.className =
                    "detail-color";

                button.title =
                    color.name;

                button.style.backgroundColor =
                    getColorValue(
                        color.name
                    );


                if (
                    index ===
                    currentColorIndex
                ) {

                    button.classList.add(
                        "selected"
                    );
                }


                button.addEventListener(
                    "click",
                    function () {

                        selectDetailColor(
                            index
                        );

                    }
                );


                colorsContainer.appendChild(
                    button
                );

            }
        );

    }


    const selectedColorName =
        document.getElementById(
            "selected-color-name"
        );


    if (selectedColorName) {

        selectedColorName.textContent =
            selectedColor.name;
    }


    const previousButton =
        document.getElementById(
            "detail-prev"
        );


    const nextButton =
        document.getElementById(
            "detail-next"
        );


    const imageCount =
        selectedColor.images.length;


    if (imageCount > 1) {

        if (previousButton) {
            previousButton.style.display =
                "flex";
        }

        if (nextButton) {
            nextButton.style.display =
                "flex";
        }

    } else {

        if (previousButton) {
            previousButton.style.display =
                "none";
        }

        if (nextButton) {
            nextButton.style.display =
                "none";
        }
    }
}


/* =========================================================
   SELECT DETAIL COLOR
========================================================= */

function selectDetailColor(colorIndex) {

    if (!currentProduct) {
        return;
    }


    currentColorIndex =
        colorIndex;


    currentImageIndex = 0;


    updateProductModal();
}


/* =========================================================
   DETAIL IMAGE NAVIGATION
========================================================= */

function previousDetailImage() {

    if (!currentProduct) {
        return;
    }


    const selectedColor =
        currentProduct.colors[
            currentColorIndex
        ];


    if (selectedColor.images.length <= 1) {
        return;
    }


    currentImageIndex--;


    if (currentImageIndex < 0) {

        currentImageIndex =
            selectedColor.images.length - 1;
    }


    updateProductModal();
}


function nextDetailImage() {

    if (!currentProduct) {
        return;
    }


    const selectedColor =
        currentProduct.colors[
            currentColorIndex
        ];


    if (selectedColor.images.length <= 1) {
        return;
    }


    currentImageIndex++;


    if (
        currentImageIndex >=
        selectedColor.images.length
    ) {

        currentImageIndex = 0;
    }


    updateProductModal();
}


/* =========================================================
   CLOSE PRODUCT
========================================================= */

function closeProduct() {

    const modal =
        document.getElementById(
            "product-modal"
        );


    if (modal) {

        modal.classList.remove(
            "active"
        );
    }


    document.body.style.overflow = "";

    currentProduct = null;
}


/* =========================================================
   DETAIL QUANTITY
========================================================= */

function increaseDetailQuantity() {

    detailQuantity++;


    const quantity =
        document.getElementById(
            "detail-quantity"
        );


    if (quantity) {

        quantity.textContent =
            detailQuantity;
    }
}


function decreaseDetailQuantity() {

    if (detailQuantity <= 1) {
        return;
    }


    detailQuantity--;


    const quantity =
        document.getElementById(
            "detail-quantity"
        );


    if (quantity) {

        quantity.textContent =
            detailQuantity;
    }
}


/* =========================================================
   ADD TO CART
========================================================= */

function addToCart(
    product,
    color,
    image,
    quantity
) {

    const existingItem =
        cart.find(function (item) {

            return (
                item.id === product.id &&
                item.color === color
            );

        });


    if (existingItem) {

        existingItem.quantity +=
            quantity;

    } else {

        cart.push({

            id: product.id,

            name: product.name,

            price: Number(product.price),

            color: color,

            image: image,

            quantity: quantity
        });
    }


    updateCart();


    showToast(
        product.name +
        " added to your cart."
    );


    const cartElement =
        document.getElementById("cart");


    if (cartElement) {

        cartElement.classList.add(
            "active"
        );
    }
}


/* =========================================================
   ADD CURRENT PRODUCT TO CART
========================================================= */

function addCurrentProductToCart() {

    if (!currentProduct) {
        return;
    }


    const selectedColor =
        currentProduct.colors[
            currentColorIndex
        ];


    const image =
        selectedColor.images[
            currentImageIndex
        ];


    addToCart(
        currentProduct,
        selectedColor.name,
        image,
        detailQuantity
    );


    closeProduct();
}


/* =========================================================
   UPDATE CART
========================================================= */

function updateCart() {

    const cartItems =
        document.getElementById(
            "cart-items"
        );


    const cartTotal =
        document.getElementById(
            "cart-total"
        );


    const cartCount =
        document.getElementById(
            "cart-count"
        );


    if (!cartItems) {
        return;
    }


    cartItems.innerHTML = "";


    if (cart.length === 0) {

        cartItems.innerHTML = `

            <div class="empty-cart">

                <p>
                    Your cart is waiting
                    for something beautiful.
                </p>

            </div>

        `;
    }


    cart.forEach(function (item, index) {

        const cartItem =
            document.createElement("div");


        cartItem.className =
            "cart-item";


        cartItem.innerHTML = `

            <img
                src="${item.image}"
                alt="${item.name}"
            >

            <div class="cart-item-info">

                <h4>
                    ${item.name}
                </h4>

                <p>
                    Color:
                    ${item.color}
                </p>

                <p>
                    $${item.price.toFixed(2)}
                </p>

                <div class="cart-quantity">

                    <button
                        type="button"
                        class="cart-minus"
                        data-index="${index}"
                    >
                        −
                    </button>

                    <span>
                        ${item.quantity}
                    </span>

                    <button
                        type="button"
                        class="cart-plus"
                        data-index="${index}"
                    >
                        +
                    </button>

                </div>

                <button
                    type="button"
                    class="remove-item"
                    data-index="${index}"
                >
                    Remove
                </button>

            </div>
        `;


        cartItems.appendChild(
            cartItem
        );

    });


    let total = 0;

    let totalQuantity = 0;


    cart.forEach(function (item) {

        total +=
            item.price *
            item.quantity;


        totalQuantity +=
            item.quantity;

    });


    if (cartTotal) {

        cartTotal.textContent =
            "$" +
            total.toFixed(2);
    }


    if (cartCount) {

        cartCount.textContent =
            totalQuantity;
    }
}


/* =========================================================
   CART BUTTON ACTIONS
========================================================= */

function changeCartQuantity(
    index,
    amount
) {

    if (!cart[index]) {
        return;
    }


    cart[index].quantity +=
        amount;


    if (
        cart[index].quantity <= 0
    ) {

        cart.splice(index, 1);
    }


    updateCart();
}


function removeCartItem(index) {

    if (!cart[index]) {
        return;
    }


    const removed =
        cart[index];


    cart.splice(index, 1);


    updateCart();


    showToast(
        removed.name +
        " removed from your cart."
    );
}


/* =========================================================
   CART TOGGLE
========================================================= */

function toggleCart() {

    const cartElement =
        document.getElementById(
            "cart"
        );


    if (!cartElement) {
        return;
    }


    cartElement.classList.toggle(
        "active"
    );
}


/* =========================================================
   SEARCH
========================================================= */

function searchProducts() {

    const input =
        document.getElementById(
            "searchInput"
        );


    if (!input) {
        return;
    }


    const searchValue =
        input.value
            .toLowerCase()
            .trim();


    const cards =
        document.querySelectorAll(
            ".card"
        );


    cards.forEach(function (card) {

        const title =
            card.querySelector("h3");


        if (!title) {
            return;
        }


        const name =
            title.textContent
                .toLowerCase();


        if (
            name.includes(searchValue)
        ) {

            card.style.display = "";

        } else {

            card.style.display = "none";
        }

    });
}


/* =========================================================
   MOBILE MENU
   THIS IS THE IMPORTANT FIX
========================================================= */

function toggleMenu() {

    const menu =
        document.getElementById(
            "mobileMenu"
        );


    const menuButton =
        document.getElementById(
            "menuToggle"
        );


    if (!menu) {
        return;
    }


    const isOpen =
        menu.classList.contains(
            "active"
        );


    if (isOpen) {

        menu.classList.remove(
            "active"
        );

        if (menuButton) {

            menuButton.classList.remove(
                "active"
            );

            menuButton.setAttribute(
                "aria-expanded",
                "false"
            );

            menuButton.setAttribute(
                "aria-label",
                "Open menu"
            );
        }

    } else {

        menu.classList.add(
            "active"
        );

        if (menuButton) {

            menuButton.classList.add(
                "active"
            );

            menuButton.setAttribute(
                "aria-expanded",
                "true"
            );

            menuButton.setAttribute(
                "aria-label",
                "Close menu"
            );
        }
    }
}


